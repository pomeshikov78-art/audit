def box(s, x, y, cx, cy, fill=None, line=None):
    sh = s.shapes.add_shape(1, Inches(x), Inches(y), Inches(cx), Inches(cy))
    sh.fill.solid(); sh.fill.fore_color.rgb = fill if fill else RGBColor(0xFF, 0xFF, 0xFF)
    if line: sh.line.color.rgb = line; sh.line.width = Pt(0.75)
    else: sh.line.fill.background()
    sh.shadow.inherit = False
    return sh

def txt(s, x, y, cx, cy, runs, size=14, color=NAVY, bold=False, align=PP_ALIGN.LEFT, spb=1.15):
    tb = s.shapes.add_textbox(Inches(x), Inches(y), Inches(cx), Inches(cy))
    tf = tb.text_frame; tf.word_wrap = True
    if isinstance(runs, str): runs = [runs]
    for i, ln in enumerate(runs):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align; p.space_after = Pt(spb * 4)
        if isinstance(ln, tuple):  # (text, size, color, bold)
            t, sz, cl, bd = ln
        else:
            t, sz, cl, bd = ln, size, color, bold
        r = p.add_run(); r.text = t
        r.font.size = Pt(sz); r.font.color.rgb = cl; r.font.bold = bd
        r.font.name = 'Calibri'
    return tb

def table(s, x, y, cx, cy, data, widths=None, fs=11, hfs=11, hfill=NAVY, colors=None):
    rows = len(data); cols = len(data[0])
    tb = s.shapes.add_table(rows, cols, Inches(x), Inches(y), Inches(cx), Inches(cy)).table
    if widths:
        tot = sum(widths)
        for j, w in enumerate(widths): tb.columns[j].width = Emu(int(Inches(cx) * w / tot))
    for i, row in enumerate(data):
        for j, cell in enumerate(row):
            c = tb.cell(i, j); c.text = str(cell)
            c.margin_left = Inches(0.06); c.margin_right = Inches(0.06)
            c.margin_top = Inches(0.02); c.margin_bottom = Inches(0.02)
            for p in c.text_frame.paragraphs:
                for r in p.runs:
                    r.font.name = 'Calibri'
                    r.font.size = Pt(hfs if i == 0 else fs)
                    if i == 0:
                        r.font.bold = True; r.font.color.rgb = WHT
                    elif colors and colors.get((i, j)):
                        r.font.color.rgb = colors[(i, j)]
            if i == 0:
                c.fill.solid(); c.fill.fore_color.rgb = hfill
            elif i % 2 == 0:
                c.fill.solid(); c.fill.fore_color.rgb = LGT
    return tb

