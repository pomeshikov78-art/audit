# -*- coding: utf-8 -*-
import formulas, re
FN="7_Оценка_актуальности_целесообразности_НИОКР.xlsx"
xl=formulas.ExcelModel().loads("output/7_Оценка_актуальности_целесообразности_НИОКР.xlsx").finish()
inp={}
# регрессия листа «Оценка»: D8..D17
ansA=["Да","Да","В основном да","В основном да","Да","Частично","Скорее нет","Н/П","Скорее нет","Да"]
for i,v in enumerate(ansA): inp[f"'[{FN}]ОЦЕНКА'!D{8+i}"]=v
# лист «Сравнение НИОКР»
rows={5:("НИОКР-А",90,88,"Нет",0),6:("НИОКР-Б",40,20,"Нет",6),7:("НИОКР-В",75,60,"Да",2),
      8:("НИОКР-Г","","","",""),9:("НИОКР-Д",88,72,"Нет",1)}
for r,(b,c,dd,e,f) in rows.items():
    inp[f"'[{FN}]СРАВНЕНИЕ НИОКР'!B{r}"]=b; inp[f"'[{FN}]СРАВНЕНИЕ НИОКР'!C{r}"]=c
    inp[f"'[{FN}]СРАВНЕНИЕ НИОКР'!D{r}"]=dd; inp[f"'[{FN}]СРАВНЕНИЕ НИОКР'!E{r}"]=e
    inp[f"'[{FN}]СРАВНЕНИЕ НИОКР'!F{r}"]=f
sol=xl.calculate(inputs=inp)
import sys
_k17=[k for k in sol if re.search(r"СРАВНЕНИЕ НИОКР'![A-K]17$",k)]
print("DEBUG row17 keys:",len(_k17),file=sys.stderr)
_ks=[k for k in sol if "СРАВНЕНИЕ" in k.upper()][-6:]
for _k in _ks: print("DEBUG tail-key:",repr(_k),file=sys.stderr)
def V(sheet,cell):
    for k,v in sol.items():
        if k.upper().endswith(f"]{sheet}'!{cell}".upper()) or k.upper().endswith(f"]{sheet.upper()}'!{cell}"):
            try: return v.value[0,0]
            except Exception: return v.value
    return "<KEY-NOT-FOUND>"
fails=0
def chk(name,got,exp):
    global fails
    okk = exp[0](got) if (isinstance(exp,tuple) and len(exp)==1 and callable(exp[0])) else (got==exp)
    print(("PASS" if okk else "FAIL"),"|",name,"=",repr(got)[:110])
    if not okk: fails+=1
# --- регрессия «Оценка» ---
chk("Оценка E18 (I_А=73.3: Σ33/n9)",round(float(V("ОЦЕНКА","E18")),1),73.3)
chk("Оценка G18 («Хорошая»)",V("ОЦЕНКА","G18"),"Хорошая")
# --- лист «Сравнение НИОКР» ---
S="СРАВНЕНИЕ НИОКР"
chk("стр5 G/H уровни В/В",(V(S,"G5"),V(S,"H5")),("Высокая","Высокая"))
chk("стр5 I рекомендация В/В",V(S,"I5"),"Продолжить работы в обычном режиме; рассмотреть ускорение НИОКР")
chk("стр5 J/K Реалистичная/Продолжение",(V(S,"J5"),V(S,"K5")),("Реалистичная","Продолжение"))
chk("стр6 I «Прекратить НИОКР»",V(S,"I6"),"Прекратить НИОКР")
chk("стр6 G/H Низкая/Критическая",(V(S,"G6"),V(S,"H6")),("Низкая","Критическая"))
chk("стр6 J/K Маловероятная/Прекращение",(V(S,"J6"),V(S,"K6")),("Маловероятная","Прекращение"))
chk("стр7 I стоп-блокировка",V(S,"I7"),(lambda x: str(x).startswith("ВНЕОЧЕРЕДНОЕ РАССМОТРЕНИЕ РУКОВОДСТВОМ"),))
chk("стр7 J/K Маловероятная/СТОП-ФАКТОР",(V(S,"J7"),V(S,"K7")),("Маловероятная","СТОП-ФАКТОР"))
chk("стр8 G/H «—/—»",(V(S,"G8"),V(S,"H8")),("—","—"))
chk("стр8 I недостаточно данных",V(S,"I8"),(lambda x:"Недостаточно данных" in str(x),))
chk("стр8 J/K «—»/Нет данных",(V(S,"J8"),V(S,"K8")),("—","Нет данных"))
chk("стр9 G/H Высокая/Хорошая",(V(S,"G9"),V(S,"H9")),("Высокая","Хорошая"))
chk("стр9 I «Продолжить при условии…»",V(S,"I9"),"Продолжить при условии устранения выявленных замечаний")
chk("стр9 J/K Реалистичная/Корректировка",(V(S,"J9"),V(S,"K9")),("Реалистичная","Корректировка"))
chk("C16 заполнено=5",int(V(S,"C16")),5)
chk("F16 средний I_А=73.3",round(float(V(S,"F16")),1),73.3)
chk("G16 средний I_Ц=60.0",round(float(V(S,"G16")),1),60.0)
chk("H16 предупреждение о стоп-факторе",V(S,"H16"),(lambda x:"стоп-фактором" in str(x),))
g17=[str(V(S,c+"17")) for c in "CDEFGHI"]
chk("C17 Продолжение: 1",g17[0],"Продолжение: 1")
chk("D17 Корректировка: 1",g17[1],"Корректировка: 1")
chk("E17 Пересмотр: 0",g17[2],"Пересмотр: 0")
chk("F17 Приостановка: 0",g17[3],"Приостановка: 0")
chk("G17 Прекращение: 1",g17[4],"Прекращение: 1")
chk("H17 СТОП-ФАКТОР: 1",g17[5],"СТОП-ФАКТОР: 1")
chk("I17 Нет данных: 1",g17[6],"Нет данных: 1")
chk("J17 флагов всего 9",V(S,"J17"),"«Красных» флагов всего: 9")
print(">>>",("ПРОВАЛЕНО: %d"%fails) if fails else "ВСЕ ФОРМУЛЫ ЛИСТА «СРАВНЕНИЕ НИОКР» + РЕГРЕССИЯ «ОЦЕНКИ» ВЕРНЫ")
