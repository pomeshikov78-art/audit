doc = Document()
st = doc.styles['Normal']; st.font.name = 'Calibri'; st.font.size = Pt(10.5)
for s in doc.sections:
    s.left_margin = s.right_margin = Cm(1.7); s.top_margin = s.bottom_margin = Cm(1.7)

def h(level, text):
    doc.add_heading(text, level=level)

def p(text, bold=False, italic=False):
    par = doc.add_paragraph()
    r = par.add_run(text); r.bold = bold; r.italic = italic
    return par

def bullets(items):
    for it in items:
        doc.add_paragraph(it, style='List Bullet')

def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers)); t.style = 'Table Grid'
    hdr = t.rows[0].cells
    for i, x in enumerate(headers):
        hdr[i].paragraphs[0].add_run(str(x)).bold = True
        for pr in hdr[i].paragraphs: pr.alignment = WD_ALIGN_PARAGRAPH.LEFT
    for row in rows:
        cells = t.add_row().cells
        for i, x in enumerate(row):
            cells[i].text = ''
            run = cells[i].paragraphs[0].add_run(str(x))
            run.font.size = Pt(9.5)
    if widths:
        for i, wd in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(wd)
    doc.add_paragraph()
    return t

