    if line.startswith('# '):
        p = doc.add_heading(line[2:], level=0)
    elif line.startswith('## '):
        doc.add_heading(line[3:], level=1)
    elif line.startswith('### '):
        doc.add_heading(line[4:], level=2)
    elif line.startswith('---'):
        doc.add_paragraph('_' * 60)
    elif line.startswith('- '):
        doc.add_paragraph(line[2:].replace('**', ''), style='List Bullet')
    elif line and line[0].isdigit() and line[:3].strip().endswith('.') and '. ' in line[:4]:
        doc.add_paragraph(line.replace('**', ''), style='List Number')
    elif line == '':
        pass
    else:
        txt = line.replace('**', '').replace('*Демо', 'Демо')
        p = doc.add_paragraph(txt)
        if line.startswith('**') or line.startswith('УТВЕРЖДАЮ'):
            for r in p.runs:
                r.bold = True
