def slide_new(bg_color=WHITE):
    s = prs.slides.add_slide(BLANK)
    r = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, SW, SH)
    r.fill.solid(); r.fill.fore_color.rgb = bg_color
    r.line.fill.background()
    r.shadow.inherit = False
    return s


def rect(s, l, t, w, h, color, line=None, shape=MSO_SHAPE.RECTANGLE):
    r = s.shapes.add_shape(shape, l, t, w, h)
    r.fill.solid(); r.fill.fore_color.rgb = color
    if line is None:
        r.line.fill.background()
    else:
        r.line.color.rgb = line; r.line.width = Pt(0.75)
    r.shadow.inherit = False
    return r


def _shrink_title(title):
    return 23 if len(title) <= 56 else 20


def txt(s, l, t, w, h, text, size=12, bold=False, color=BLACK, align=PP_ALIGN.LEFT,
        italic=False, anchor=MSO_ANCHOR.TOP, spacing=1.0):
    tb = s.shapes.add_textbox(l, t, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    tf.margin_left = tf.margin_right = Inches(0.02)
    tf.margin_top = tf.margin_bottom = Inches(0.01)
    lines = text.split("\n")
    for i, ln in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        p.line_spacing = spacing
        run = p.add_run(); run.text = ln
        f = run.font
        f.name = FONT; f.size = Pt(size); f.bold = bold; f.italic = italic; f.color.rgb = color
    return tb


def header(s, kicker, title, page=None):
    rect(s, 0, 0, SW, Inches(1.06), NAVY)
