def star(i):
    return " ★" if "★" in QS[i][0] else ""

def qtext(i):
    return QS[i][0].replace(" ★", "").strip()

def block_table(idxs, names=None):
    out = ["| № | Критерий | Вопрос | Что проверяется | Балл 5 | Балл 3 | Балл 1 |",
           "| --- | --- | --- | --- | --- | --- | --- |"]
    for k, i in enumerate(idxs):
        nm = (names[k] if names else "—")
        a = ANCH[i]
        out.append("| %d%s | %s | %s | %s | %s | %s | %s |" % (
            i + 1, star(i), nm, qtext(i), QS[i][1], a[0], a[1], a[2]))
    return "\n".join(out)

