PASS = FAIL = 0
FAILED = []

def ck(name, cond, got=None, want=None):
    global PASS, FAIL
    if cond:
        PASS += 1; print('  ✔', name)
    else:
        FAIL += 1; FAILED.append(name); print('  ✘ %s | got=%r want=%r' % (name, got, want))

def num(v):
    try:
        return float(v)
    except Exception:
        return None

def close(name, v, want, tol=0.01):
    n = num(v); ck(name, n is not None and abs(n - want) <= tol, v, round(want, 4))

def eq(name, v, want):
    ck(name, v == want, v, want)

def has(name, v, sub):
    ck(name, isinstance(v, str) and sub in v, v, 'contains ' + repr(sub))

