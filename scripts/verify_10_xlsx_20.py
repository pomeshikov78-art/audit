# -*- coding: utf-8 -*-
"""Этап 20 (v20.0): верификация 10_Чек-лист_ЭО_НИОКР_22_вопроса_v20.xlsx
независимым пересчётом (библиотека formulas). Группа до 10 экспертов.
Контрольные примеры К-1…К-10: индексы I_A/I_C, правило Н/О (≤2 / >2),
групповое среднее, σ и согласованность, повопросные статистики, стоп-факторы
и оверрайд матрицы, «красные» групповые сигналы, блокировка рекомендации
при неполной оценке, расчёт на 10 экспертов, пустые анкеты в группе 10."""
import shutil, io, os
import openpyxl, formulas

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'output', '10_Чек-лист_ЭО_НИОКР_22_вопроса_v20.xlsx')
TMP = '/tmp/eo20_case.xlsx'

ROWS_A = list(range(9, 19))    # А1..А10
ROWS_C = list(range(21, 33))   # Ц1..Ц12
ROWS_SF = list(range(45, 50))  # СФ1..СФ5
ROWS_KV = list(range(53, 62))  # КВ1..КВ9
KV_DIR = ['neg', 'neg', 'neg', 'neg', 'neg', 'neg', 'pos', 'pos', 'neg']

# --- адреса листа «Свод» (v20) ---
GRP, SIG, CON = 15, 16, 17          # групповые / σ / согласованность
Q0 = 21                              # вопросы: А1=21…А10=30, Ц1=31…Ц12=42
QCNT = 44                            # число разногласий
SF0, SFF = 48, 54                    # СФ 48..52, флаг 54
KV0, KVL = 58, 68                    # КВ 58..66, перечень 68
ZA, ZC = 71, 72                      # зоны
REC, OVR = 79, 80                    # рекомендация / оверрайд
LOWR, DISR = 82, 83                  # списки

PASS = FAIL = 0
FAILED = []

def ck(name, cond, got=None, want=None):
    global PASS, FAIL
    if cond:
        PASS += 1; print('  ✔', name)
    else:
        FAIL += 1; FAILED.append(name); print('  ✘ %s | got=%r want=%r' % (name, got, want))

def num(v):
    try:
        return float(v)
    except Exception:
        return None

def close(name, v, want, tol=0.01):
    n = num(v); ck(name, n is not None and abs(n - want) <= tol, v, round(want, 4))

def eq(name, v, want):
    ck(name, v == want, v, want)

def has(name, v, sub):
    ck(name, isinstance(v, str) and sub in v, v, 'contains ' + repr(sub))

def run(fill):
    """fill: dict expert(1-10) -> {'A':[10], 'C':[12], 'SF':[5], 'KV':[9]} (значения или None)."""
    shutil.copy(SRC, TMP)
    wb = openpyxl.load_workbook(TMP)
    for e, d in fill.items():
        ws = wb['Э%d' % e]
        if d is None:
            continue
        for i, v in enumerate(d['A']):
            if v is not None: ws.cell(row=ROWS_A[i], column=4, value=v)
        for i, v in enumerate(d['C']):
            if v is not None: ws.cell(row=ROWS_C[i], column=4, value=v)
        for i, v in enumerate(d['SF']):
            if v is not None: ws.cell(row=ROWS_SF[i], column=3, value=v)
        for i, v in enumerate(d['KV']):
            if v is not None: ws.cell(row=ROWS_KV[i], column=3, value=v)
    wb.save(TMP)
    xl = formulas.ExcelModel().loads(TMP).finish()
    sol = xl.calculate()
    pref = "'[eo20_case.xlsx]%s'!%s"
    def get(sheet, cell):
        v = sol[pref % (sheet.upper(), cell)].value
        try:
            v = v[0, 0]
        except Exception:
            pass
        return v
    return get

def exp(a_all=None, c_all=None, a=None, c=None, sf=None, kv=None):
    A = a or [a_all] * 10
    C = c or [c_all] * 12
    SF = sf or ['Нет'] * 5
    KV = kv or [(5 if d == 'neg' else 1) for d in KV_DIR]
    return {'A': A, 'C': C, 'SF': SF, 'KV': KV}

print('К-1: благополучная НИОКР (все 5, три эксперта) → В/В, «Продолжить НИОКР», без сигналов')
g = run({1: exp(5, 5), 2: exp(5, 5), 3: exp(5, 5)})
close('Э1 I_A = 5', g('Э1', 'D34'), 5)
close('Свод I_A гр = 5', g('Свод', 'B%d' % GRP), 5)
close('Свод I_C гр = 5', g('Свод', 'C%d' % GRP), 5)
eq('зона I_A = В', g('Свод', 'B%d' % ZA), 'В')
eq('зона I_C = В', g('Свод', 'B%d' % ZC), 'В')
eq('матрица: Продолжить НИОКР', g('Свод', 'B%d' % REC), 'Продолжить НИОКР')
eq('оверрайд не сработал', g('Свод', 'B%d' % OVR), 'Продолжить НИОКР')
eq('СФ не выявлены', g('Свод', 'B%d' % SFF), 'СТОП-ФАКТОРЫ НЕ ВЫЯВЛЕНЫ')
eq('КВ сигналов нет', g('Свод', 'B%d' % KVL), 'не выявлены')
eq('σ = 0 → высокая согласованность', g('Свод', 'B%d' % CON), 'Высокая')
eq('вопрос А1 среднее 5', g('Свод', 'L%d' % Q0), 5)
eq('вопрос А1 σ = 0', g('Свод', 'P%d' % Q0), 0)
eq('флагов разногласия нет', g('Свод', 'Q%d' % Q0), '')
close('Панель: I_A сквозная ссылка', g('Панель', 'B3'), 5)
eq('Панель: рекомендация', g('Панель', 'B8'), 'Продолжить НИОКР')
has('заключение: высокий уровень', g('Заключение', 'B7'), 'высокому')

print('К-2: актуальна, но сложности реализации (С-1 апробации) → В/С')
C2 = [2, 2, 4, 2, 2, 4, 4, 4, 4, 4, 2, 4]  # Ц1,Ц2,Ц4,Ц5,Ц11 = 2
g = run({1: exp(5, c=C2), 2: exp(5, c=C2), 3: exp(5, c=C2)})
close('I_A = 5', g('Свод', 'B%d' % GRP), 5)
close('I_C = 3.1667', g('Свод', 'C%d' % GRP), sum(C2) / 12.0)
eq('зона I_C = С', g('Свод', 'B%d' % ZC), 'С')
eq('матрица: Продолжить с корректировкой', g('Свод', 'B%d' % REC), 'Продолжить с корректировкой')
eq('А1 без низкой оценки', g('Свод', 'R%d' % Q0), '')
eq('низкая оценка по Ц1 (строка 31)', g('Свод', 'R%d' % (Q0 + 10)), 'НИЗКАЯ')
has('список низких содержит Ц1', g('Свод', 'B%d' % LOWR), 'Ц1')

print('К-3: высокие индексы + стоп-фактор СФ1 («Да» у одного) → оверрайд')
g = run({1: exp(5, 5, sf=['Да', 'Нет', 'Нет', 'Нет', 'Нет']), 2: exp(5, 5), 3: exp(5, 5)})
eq('СФ выявлен', g('Свод', 'B%d' % SFF), 'СТОП-ФАКТОР ВЫЯВЛЕН')
eq('счётчик «Да» СФ1 = 1', g('Свод', 'C%d' % SF0), 1)
eq('матрица без оверрайда: Продолжить', g('Свод', 'B%d' % REC), 'Продолжить НИОКР')
has('оверрайд понизил', g('Свод', 'B%d' % OVR), 'ПОНИЖЕНИЕ')
has('заключение упоминает стоп-фактор', g('Заключение', 'B13'), 'СТОП-ФАКТОР ВЫЯВЛЕН')

print('К-4: Н/О = 3 у эксперта 1 по актуальности → его I_A не рассчитан')
d1 = exp(4, 4); d1['A'] = ['Н/О', 'Н/О', 'Н/О'] + [4] * 7
g = run({1: d1, 2: exp(4, 4), 3: exp(4, 4)})
eq('Э1 I_A = НЕ РАССЧИТАН', g('Э1', 'D34'), 'НЕ РАССЧИТАН')
close('Э1 I_C = 4', g('Э1', 'D35'), 4)
eq('Э1 счётчик Н/О = 3', g('Э1', 'B37'), 3)
close('групповой I_A = 4 (без Э1)', g('Свод', 'B%d' % GRP), 4)
eq('статус Э1 = ОК (частичный)', g('Свод', 'D5'), 'ОК')

print('К-5: существенные разногласия (5/1/3) → σ=1.633, флаги по 10 вопросам А')
g = run({1: exp(5, 4), 2: exp(1, 4), 3: exp(3, 4)})
close('I_A гр = 3', g('Свод', 'B%d' % GRP), 3)
close('σ(I_A) = 1.6330', g('Свод', 'B%d' % SIG), 1.632993)
eq('согласованность: существенные', g('Свод', 'B%d' % CON), 'Существенные разногласия')
eq('А1: среднее 3', g('Свод', 'L%d' % Q0), 3)
eq('А1: min 1', g('Свод', 'M%d' % Q0), 1)
eq('А1: max 5', g('Свод', 'N%d' % Q0), 5)
eq('А1: разброс 4', g('Свод', 'O%d' % Q0), 4)
eq('А1: флаг РАЗНОГЛАСИЕ', g('Свод', 'Q%d' % Q0), 'РАЗНОГЛАСИЕ')
eq('число разногласий = 10', g('Свод', 'B%d' % QCNT), 10)
has('заключение: обсуждение', g('Заключение', 'B11'), 'обсуждение')

print('К-6: «красные» групповые сигналы (КВ1 neg ≤2 у двоих; КВ7 pos ≥4 у двоих)')
kv1 = [1, 5, 5, 5, 5, 5, 5, 5, 5]
kv2 = [1, 5, 5, 5, 5, 5, 4, 5, 5]
kv3 = [5, 5, 5, 5, 5, 5, 1, 5, 5]
g = run({1: exp(4, 4, kv=kv1), 2: exp(4, 4, kv=kv2), 3: exp(4, 4, kv=kv3)})
eq('КВ1: 2 сигнала', g('Свод', 'C%d' % KV0), 2)
eq('КВ1: ГРУППОВОЙ СИГНАЛ', g('Свод', 'D%d' % KV0), 'ГРУППОВОЙ СИГНАЛ')
eq('КВ7: 2 сигнала (позитивный)', g('Свод', 'C%d' % (KV0 + 6)), 2)
eq('КВ7: ГРУППОВОЙ СИГНАЛ', g('Свод', 'D%d' % (KV0 + 6)), 'ГРУППОВОЙ СИГНАЛ')
has('перечень содержит КВ1', g('Свод', 'B%d' % KVL), 'КВ1')
has('перечень содержит КВ7', g('Свод', 'B%d' % KVL), 'КВ7')
eq('КВ9: единичный сигнал не групповой', g('Свод', 'D%d' % (KV0 + 8)), '')

print('К-7: один эксперт, 2 Н/О → индекс считается; σ = н/д; пустые анкеты 2–10')
d1 = exp(4, 4); d1['A'] = ['Н/О', 'Н/О'] + [4] * 8
g = run({1: d1})
close('Э1 I_A = 4', g('Э1', 'D34'), 4)
close('групповой I_A = 4', g('Свод', 'B%d' % GRP), 4)
eq('σ(I_A) = н/д (один эксперт)', g('Свод', 'B%d' % SIG), 'н/д')
eq('статус пустой анкеты Э2', g('Свод', 'D6'), 'НЕ ЗАПОЛНЕНА')
eq('статус пустой анкеты Э10', g('Свод', 'D14'), 'НЕ ЗАПОЛНЕНА')

print('К-8: у всех >2 Н/О по актуальности → I_A гр = н/д, рекомендация не формируется')
d = exp(4, 4); d['A'] = ['Н/О'] * 4 + [4] * 6
g = run({1: dict(d), 2: dict(d)})
eq('Э1 I_A = НЕ РАССЧИТАН', g('Э1', 'D34'), 'НЕ РАССЧИТАН')
eq('I_A гр = н/д', g('Свод', 'B%d' % GRP), 'н/д')
eq('зона I_A = н/д', g('Свод', 'B%d' % ZA), 'н/д')
has('рекомендация не формируется', g('Свод', 'B%d' % REC), 'НЕ ФОРМИРУЕТСЯ')
has('заключение: индекс не рассчитан', g('Заключение', 'B7'), 'не рассчитан')

print('К-9: полные 10 экспертов (9×5 и 1×1 по А) → I_A=4.6, σ=1.2, 10 флагов, В/В')
fill = {e: exp(5, 5) for e in range(1, 10)}
fill[10] = exp(1, 5)
g = run(fill)
close('I_A гр = 4.6', g('Свод', 'B%d' % GRP), 4.6)
close('I_C гр = 5', g('Свод', 'C%d' % GRP), 5)
close('σ(I_A) = 1.2', g('Свод', 'B%d' % SIG), 1.2)
eq('согласованность: существенные', g('Свод', 'B%d' % CON), 'Существенные разногласия')
eq('А1: min 1 (10 экспертов)', g('Свод', 'M%d' % Q0), 1)
eq('А1: max 5', g('Свод', 'N%d' % Q0), 5)
close('А1: σ = 1.2', g('Свод', 'P%d' % Q0), 1.2)
eq('А1: флаг РАЗНОГЛАСИЕ', g('Свод', 'Q%d' % Q0), 'РАЗНОГЛАСИЕ')
eq('число разногласий = 10', g('Свод', 'B%d' % QCNT), 10)
eq('зона I_A = В', g('Свод', 'B%d' % ZA), 'В')
eq('матрица: Продолжить НИОКР', g('Свод', 'B%d' % REC), 'Продолжить НИОКР')
has('перечень разногласий содержит А10', g('Свод', 'B%d' % DISR), 'А10')
close('Э10 I_A = 1', g('Э10', 'D34'), 1)

print('К-10: 6 заполненных из 10 → групповое среднее по шести; σ считается')
g = run({1: exp(4, 4), 2: exp(4, 4), 3: exp(5, 4), 4: exp(3, 4), 5: exp(4, 5), 6: exp(4, 3)})
close('I_A гр = 4', g('Свод', 'B%d' % GRP), 4)
close('I_C гр = 4', g('Свод', 'C%d' % GRP), 4)
close('σ(I_A) = 0.5774', g('Свод', 'B%d' % SIG), 0.57735)
eq('согласованность: приемлемая', g('Свод', 'B%d' % CON), 'Приемлемая')
eq('статус Э7 = НЕ ЗАПОЛНЕНА', g('Свод', 'D11'), 'НЕ ЗАПОЛНЕНА')
eq('матрица: Продолжить НИОКР', g('Свод', 'B%d' % REC), 'Продолжить НИОКР')

print()
print('ИТОГ: %d проверок, %d ошибок' % (PASS + FAIL, FAIL))
if FAILED:
    print('ПРОВАЛЕНО:', FAILED)
    raise SystemExit(1)
print('ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ')
