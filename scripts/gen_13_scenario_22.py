import docx
from docx.shared import Pt
from docx.enum.table import WD_TABLE_ALIGNMENT

doc = docx.Document()
stl = doc.styles['Normal']
stl.font.name = 'Calibri'; stl.font.size = Pt(10.5)

def add_md_table(lines, start):
    rows = []
    i = start
    while i < len(lines) and lines[i].startswith('|'):
        rows.append(lines[i]); i += 1
    cells = [[c.strip() for c in r.strip('|').split('|')] for r in rows]
    cells = [r for j, r in enumerate(cells) if not (j == 1 and all(set(c) <= set('-: ') for c in r))]
    if not cells:
        return i
    ncol = max(len(r) for r in cells)
    t = doc.add_table(rows=0, cols=ncol)
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for r in cells:
        row = t.add_row().cells
        for j in range(ncol):
            txt = r[j] if j < len(r) else ''
            txt = txt.replace('**', '').replace('☐', '[ ]')
            p = row[j].paragraphs[0]
            p.add_run(txt).font.size = Pt(9)
    doc.add_paragraph()
    return i

i = 0
while i < len(L):
    line = L[i]
    if line.startswith('|'):
        i = add_md_table(L, i); continue
    if line.startswith('# '):
        doc.add_heading(line[2:], level=0)
    elif line.startswith('## '):
        doc.add_heading(line[3:], level=1)
    elif line.startswith('### '):
        doc.add_heading(line[4:], level=2)
    elif line.startswith('---'):
        doc.add_paragraph('_' * 60)
    elif line.startswith('- '):
        doc.add_paragraph(line[2:].replace('**', ''), style='List Bullet')
    elif line and line[0].isdigit() and line[:3].strip().endswith('.') and '. ' in line[:4]:
        doc.add_paragraph(line.replace('**', ''), style='List Number')
    elif line == '':
        pass
    else:
        txt = line.replace('**', '')
        p = doc.add_paragraph(txt)
        if line.startswith('**') or line.startswith('ПРОТОКОЛ'):
            for r in p.runs:
                r.bold = True
    i += 1

doc.save(OUT_DX)
