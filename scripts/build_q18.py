# -*- coding: utf-8 -*-
# Этап 18Б: консолидация банка данных модели v18.0 → scripts/data/q18.json
# Источники: data9.json (вопросы/справочники из «Научно.docx»), Excel № 9 (коды, секции, имена блоков,
# адреса ячеек для импорта), семантическая карта миграции 31→30 (проектирование этапа 18Б).
import json, openpyxl

d = json.load(open('scripts/data/data9.json', encoding='utf-8'))
c9 = json.load(open('scripts/data/cells9.json', encoding='utf-8'))
wb = openpyxl.load_workbook('output/9_Калькулятор_аудита_НИОКР_v2.xlsx')

DIRS = ['Актуальность', 'Целесообразность', 'Результативность']
SEC2DIR = {'А': 0, 'Б': 1, 'В': 2}

# ---------- Краткий (15) ----------
K = []
for q in d['Q15']:
    code = f"{q['sec']}{q['n']}"
    K.append({'i': q['n'] - 1, 'code': code, 'sec': q['sec'], 'dir': SEC2DIR[q['sec']],
              'q': q['q'], 'a5': q.get('a5', ''), 'a3': q.get('a3', ''), 'a0': q.get('a0', ''), 'w': 1})
assert len(K) == 15

# ---------- Средний (30) ----------
S = []
for i, q in enumerate(d['Q30']):
    sec = q['code'][0]
    anch = d.get('ANCH30', {}).get(q['code'])
    S.append({'i': i, 'code': q['code'], 'sec': sec, 'dir': SEC2DIR[sec], 'q': q['q'],
              'check': q.get('check', ''), 'ev': q.get('ev', ''), 'w': q['w'], 'anch': anch})
assert len(S) == 30
for sec in 'АБВ':
    tot = sum(x['w'] for x in S if x['sec'] == sec)
    assert abs(tot - 10) < 1e-9, (sec, tot)

# ---------- Полный (60) ----------
blk_names = [wb['Полный_60'][f'B{r}'].value for r in range(69, 81)]
blocks = []
for j, b in enumerate(d['BLOCKS60']):
    code, n1, n2, w = b
    blocks.append({'code': code, 'name': blk_names[j], 'from': n1, 'to': n2, 'w': w,
                   'dir': SEC2DIR[code[0]], 'row': 69 + j})
P = []
for i, q in enumerate(d['Q60']):
    n = q['n']
    blk = next(b for b in blocks if b['from'] <= n <= b['to'])
    P.append({'i': i, 'n': n, 'code': str(n), 'blk': blk['code'], 'sec': blk['code'][0],
              'dir': SEC2DIR[blk['code'][0]], 'q': q['q'], 'est': q.get('est', ''), 'ev': q.get('ev', ''), 'w': 1})
assert len(P) == 60
tot_by_dir = {}
for b in blocks:
    tot_by_dir[b['dir']] = tot_by_dir.get(b['dir'], 0) + b['w']
assert all(abs(v - 1) < 1e-9 for v in tot_by_dir.values()), tot_by_dir

# ---------- авторекомендации ----------
auto_rec = []
for rule, rec in d['AUTO_REC']:
    code, le = rule.replace(' ', '').split('<=')
    auto_rec.append({'code': code, 'le': int(le), 'rec': rec})
assert len(auto_rec) == 15 and all(a['le'] == 2 for a in auto_rec)

