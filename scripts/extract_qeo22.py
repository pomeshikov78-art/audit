OUT = sys.argv[2] if len(sys.argv) > 2 else 'scripts/data/qeo22.json'

text = io.open(SRC, encoding='utf-8').read()

# --- блок приложения с якорями: от "### 2. Актуальность НИОКР" до "### 4. Правила применения пояснений"
start = text.index('### 2. Актуальность НИОКР')
end = text.index('### 4. Правила применения пояснений')
block = text[start:end]

# разбиваем на вопросы
parts = re.split(r'####\s+Вопрос\s+(\d+)\.\s*(.+)', block)
# parts: [pre, num, title, body, num, title, body, ...]
entries = []
i = 1
while i < len(parts):
    num = int(parts[i]); title = parts[i+1].strip(); body = parts[i+2]
    anchors = {}
    for m in re.finditer(r'-\s+\*\*(\d)\*\*\s+—\s*(.+)', body):
        anchors[m.group(1)] = m.group(2).strip()
    entries.append({'n': num, 'q': title, 'a': anchors})
    i += 3

assert len(entries) == 22, len(entries)
for e in entries:
    assert sorted(e['a']) == ['1','2','3','4','5'], (e['n'], sorted(e['a']))

