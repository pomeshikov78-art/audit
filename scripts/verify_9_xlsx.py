PASS = FAIL = 0
FAILED = []

def ck(name, cond, got=None, want=None):
    global PASS, FAIL
    if cond: PASS += 1; print(f"  ✔ {name}")
    else:
        FAIL += 1; FAILED.append(name)
        print(f"  ✘ {name} | got={got!r} want={want!r}")

def num(v):
    try: return float(v)
    except Exception: return None

def close(name, v, want, tol=0.051):
    n = num(v)
    ck(name, n is not None and abs(n - want) <= tol, v, f"≈{want}")

def eq(name, v, want):
    ck(name, v == want, v, want)

def has(name, v, sub):
    ck(name, isinstance(v, str) and sub in v, v, f"contains {sub!r}")

def mkcase(mods):
    """mods: list of (sheet, cell, value). Всегда подменяем TODAY() в панели (библиотека)."""
    wb = openpyxl.load_workbook(SRC)
    p = wb['Панель_руководителя']
    p['B29'] = '=IFERROR(IF(ISNUMBER(Паспорт_НИОКР!$C$13),Паспорт_НИОКР!$C$13-DATE(2026,11,3),""),"")'
    for sheet, cell, val in mods:
        wb[sheet][cell] = val
    wb.save(TMP)

SOL_KEYS = {}
def solve():
    xl = formulas.ExcelModel().loads(TMP).finish()
    sol = xl.calculate()
    m = {}
    for k in sol:
        ku = k.upper()
        if ']' in ku and "'!" in ku:
            ref = ku.split(']', 1)[1]
            sh, cl = ref.split("'!")
            m[(sh, cl)] = sol[k]
    return m

def val(sol, sheet, cell):
    e = sol.get((sheet.upper(), cell.upper()))
    if e is None: return None
    try:
        v = e.value[0, 0]
    except Exception:
        try: v = e.value
        except Exception: return None
    return v

def G(sol, sheet, cell):
    v = val(sol, sheet, cell)
    if v is None: return None
    if hasattr(v, 'item'):
        try: return v.item()
        except Exception: pass
    return v

def setall(sheet, col, r1, r2, value):
    return [(sheet, f'{col}{r}', value) for r in range(r1, r2 + 1)]

