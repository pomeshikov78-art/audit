    C = c or [c_all] * 12
    SF = sf or ['Нет'] * 5
    KV = kv or [(5 if d == 'neg' else 1) for d in KV_DIR]
    return {'A': A, 'C': C, 'SF': SF, 'KV': KV, 'R': r, 'w': w}

