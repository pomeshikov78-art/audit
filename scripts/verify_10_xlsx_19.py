# -*- coding: utf-8 -*-
"""Этап 19 (v19.0): верификация 10_Чек-лист_ЭО_НИОКР_22_вопроса_v19.xlsx
независимым пересчётом (библиотека formulas). Контрольные примеры К-1…К-8:
индексы I_A/I_C, правило Н/О (≤2 / >2), групповое среднее, σ и согласованность,
повопросные статистики, стоп-факторы и оверрайд матрицы, «красные» групповые
сигналы, блокировка рекомендации при неполной оценке."""
import shutil, io, os
import openpyxl, formulas

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'output', '10_Чек-лист_ЭО_НИОКР_22_вопроса_v19.xlsx')
TMP = '/tmp/eo19_case.xlsx'

ROWS_A = list(range(9, 19))    # А1..А10
ROWS_C = list(range(21, 33))   # Ц1..Ц12
ROWS_SF = list(range(45, 50))  # СФ1..СФ5
ROWS_KV = list(range(53, 62))  # КВ1..КВ9
KV_DIR = ['neg', 'neg', 'neg', 'neg', 'neg', 'neg', 'pos', 'pos', 'neg']

PASS = FAIL = 0
FAILED = []

def ck(name, cond, got=None, want=None):
    global PASS, FAIL
    if cond:
        PASS += 1; print('  ✔', name)
    else:
        FAIL += 1; FAILED.append(name); print('  ✘ %s | got=%r want=%r' % (name, got, want))

def num(v):
    try:
        return float(v)
    except Exception:
        return None

def close(name, v, want, tol=0.01):
    n = num(v); ck(name, n is not None and abs(n - want) <= tol, v, round(want, 4))

def eq(name, v, want):
    ck(name, v == want, v, want)

def has(name, v, sub):
    ck(name, isinstance(v, str) and sub in v, v, 'contains ' + repr(sub))

def run(fill):
    """fill: dict expert(1-5) -> {'A':[10], 'C':[12], 'SF':[5], 'KV':[9]} (значения или None)."""
    shutil.copy(SRC, TMP)
    wb = openpyxl.load_workbook(TMP)
    for e, d in fill.items():
        ws = wb['Э%d' % e]
        if d is None:
            continue
        for i, v in enumerate(d['A']):
            if v is not None: ws.cell(row=ROWS_A[i], column=4, value=v)
        for i, v in enumerate(d['C']):
            if v is not None: ws.cell(row=ROWS_C[i], column=4, value=v)
        for i, v in enumerate(d['SF']):
            if v is not None: ws.cell(row=ROWS_SF[i], column=3, value=v)
        for i, v in enumerate(d['KV']):
            if v is not None: ws.cell(row=ROWS_KV[i], column=3, value=v)
    wb.save(TMP)
    xl = formulas.ExcelModel().loads(TMP).finish()
    sol = xl.calculate()
    pref = "'[eo19_case.xlsx]%s'!%s"
    def get(sheet, cell):
        v = sol[pref % (sheet.upper(), cell)].value
        try:
            v = v[0, 0]
        except Exception:
            pass
        return v
    return get

def exp(a_all=None, c_all=None, a=None, c=None, sf=None, kv=None):
    A = a or [a_all] * 10
    C = c or [c_all] * 12
    SF = sf or ['Нет'] * 5
    KV = kv or [(5 if d == 'neg' else 1) for d in KV_DIR]
    return {'A': A, 'C': C, 'SF': SF, 'KV': KV}

print('К-1: благополучная НИОКР (все 5) → В/В, «Продолжить НИОКР», без сигналов')
g = run({1: exp(5, 5), 2: exp(5, 5), 3: exp(5, 5)})
close('Э1 I_A = 5', g('Э1', 'D34'), 5)
close('Свод I_A гр = 5', g('Свод', 'B9'), 5)
close('Свод I_C гр = 5', g('Свод', 'C9'), 5)
eq('зона I_A = В', g('Свод', 'B67'), 'В')
eq('зона I_C = В', g('Свод', 'B68'), 'В')
eq('матрица: Продолжить НИОКР', g('Свод', 'B75'), 'Продолжить НИОКР')
eq('оверрайд не сработал', g('Свод', 'B76'), 'Продолжить НИОКР')
eq('СФ не выявлены', g('Свод', 'B50'), 'СТОП-ФАКТОРЫ НЕ ВЫЯВЛЕНЫ')
eq('КВ сигналов нет', g('Свод', 'B64'), 'не выявлены')
eq('σ = 0 → высокая согласованность', g('Свод', 'B13'), 'Высокая')
eq('вопрос А1 среднее 5', g('Свод', 'G18'), 5)
eq('вопрос А1 σ = 0', g('Свод', 'K18'), 0)
eq('флагов разногласия нет', g('Свод', 'L18'), '')
has('заключение: высокий уровень', g('Заключение', 'B7'), 'высокому')

print('К-2: актуальна, но сложности реализации (С-1 апобации) → В/С')
C2 = [2, 2, 4, 2, 2, 4, 4, 4, 4, 4, 2, 4]  # Ц1,Ц2,Ц4,Ц5,Ц11 = 2
g = run({1: exp(5, c=C2), 2: exp(5, c=C2), 3: exp(5, c=C2)})
close('I_A = 5', g('Свод', 'B9'), 5)
close('I_C = 3.1667', g('Свод', 'C9'), sum(C2) / 12.0)
eq('зона I_C = С', g('Свод', 'B68'), 'С')
eq('матрица: Продолжить с корректировкой', g('Свод', 'B75'), 'Продолжить с корректировкой')
eq('низкая оценка Ц1', g('Свод', 'M18'), '')
eq('низкая оценка по Ц1 (строка 28)', g('Свод', 'M28'), 'НИЗКАЯ')
has('список низких содержит Ц1', g('Свод', 'B78'), 'Ц1')

print('К-3: высокие индексы + стоп-фактор СФ1 («Да» у одного) → оверрайд')
g = run({1: exp(5, 5, sf=['Да', 'Нет', 'Нет', 'Нет', 'Нет']), 2: exp(5, 5), 3: exp(5, 5)})
eq('СФ выявлен', g('Свод', 'B50'), 'СТОП-ФАКТОР ВЫЯВЛЕН')
eq('счётчик «Да» СФ1 = 1', g('Свод', 'C44'), 1)
eq('матрица без оверрайда: Продолжить', g('Свод', 'B75'), 'Продолжить НИОКР')
has('оверрайд понизил', g('Свод', 'B76'), 'ПОНИЖЕНИЕ')
has('заключение упоминает стоп-фактор', g('Заключение', 'B13'), 'СТОП-ФАКТОР ВЫЯВЛЕН')

print('К-4: Н/О = 3 у эксперта 1 по актуальности → его I_A не рассчитан')
d1 = exp(4, 4); d1['A'] = ['Н/О', 'Н/О', 'Н/О'] + [4] * 7
g = run({1: d1, 2: exp(4, 4), 3: exp(4, 4)})
eq('Э1 I_A = НЕ РАССЧИТАН', g('Э1', 'D34'), 'НЕ РАССЧИТАН')
close('Э1 I_C = 4', g('Э1', 'D35'), 4)
eq('Э1 счётчик Н/О = 3', g('Э1', 'B37'), 3)
close('групповой I_A = 4 (без Э1)', g('Свод', 'B9'), 4)
eq('статус Э1 = ОК (частичный)', g('Свод', 'D5'), 'ОК')

print('К-5: существенные разногласия (5/1/3) → σ=1.633, флаги по 10 вопросам А')
g = run({1: exp(5, 4), 2: exp(1, 4), 3: exp(3, 4)})
close('I_A гр = 3', g('Свод', 'B9'), 3)
close('σ(I_A) = 1.6330', g('Свод', 'B12'), 1.632993)
eq('согласованность: существенные', g('Свод', 'B13'), 'Существенные разногласия')
eq('А1: среднее 3', g('Свод', 'G18'), 3)
eq('А1: min 1', g('Свод', 'H18'), 1)
eq('А1: max 5', g('Свод', 'I18'), 5)
eq('А1: разброс 4', g('Свод', 'J18'), 4)
eq('А1: флаг РАЗНОГЛАСИЕ', g('Свод', 'L18'), 'РАЗНОГЛАСИЕ')
eq('число разногласий = 10', g('Свод', 'B40'), 10)
has('заключение: обсуждение', g('Заключение', 'B11'), 'обсуждение')

print('К-6: «красные» групповые сигналы (КВ1 neg ≤2 у двоих; КВ7 pos ≥4 у двоих)')
kv1 = [1, 5, 5, 5, 5, 5, 5, 5, 5]
kv2 = [1, 5, 5, 5, 5, 5, 4, 5, 5]
kv3 = [5, 5, 5, 5, 5, 5, 1, 5, 5]
g = run({1: exp(4, 4, kv=kv1), 2: exp(4, 4, kv=kv2), 3: exp(4, 4, kv=kv3)})
eq('КВ1: 2 сигнала', g('Свод', 'C54'), 2)
eq('КВ1: ГРУППОВОЙ СИГНАЛ', g('Свод', 'D54'), 'ГРУППОВОЙ СИГНАЛ')
eq('КВ7: 2 сигнала (позитивный)', g('Свод', 'C60'), 2)
eq('КВ7: ГРУППОВОЙ СИГНАЛ', g('Свод', 'D60'), 'ГРУППОВОЙ СИГНАЛ')
has('перечень содержит КВ1', g('Свод', 'B64'), 'КВ1')
has('перечень содержит КВ7', g('Свод', 'B64'), 'КВ7')
eq('КВ9: единичный сигнал не групповой', g('Свод', 'D62'), '')

print('К-7: один эксперт, 2 Н/О → индекс считается; σ = н/д')
d1 = exp(4, 4); d1['A'] = ['Н/О', 'Н/О'] + [4] * 8
g = run({1: d1})
close('Э1 I_A = 4', g('Э1', 'D34'), 4)
close('групповой I_A = 4', g('Свод', 'B9'), 4)
eq('σ(I_A) = н/д (один эксперт)', g('Свод', 'B12'), 'н/д')
eq('статусы пустых анкет', g('Свод', 'D6'), 'НЕ ЗАПОЛНЕНА')

print('К-8: у всех >2 Н/О по актуальности → I_A гр = н/д, рекомендация не формируется')
d = exp(4, 4); d['A'] = ['Н/О'] * 4 + [4] * 6
g = run({1: dict(d), 2: dict(d)})
eq('Э1 I_A = НЕ РАССЧИТАН', g('Э1', 'D34'), 'НЕ РАССЧИТАН')
eq('I_A гр = н/д', g('Свод', 'B9'), 'н/д')
eq('зона I_A = н/д', g('Свод', 'B67'), 'н/д')
has('рекомендация не формируется', g('Свод', 'B75'), 'НЕ ФОРМИРУЕТСЯ')
has('заключение: индекс не рассчитан', g('Заключение', 'B7'), 'не рассчитан')

print()
print('ИТОГ: %d проверок, %d ошибок' % (PASS + FAIL, FAIL))
if FAILED:
    print('ПРОВАЛЕНО:', FAILED)
    raise SystemExit(1)
print('ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ')
